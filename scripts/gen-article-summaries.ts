/**
 * Build step: writes src/data/articles.summary.ts (title + description of every guide in
 * every language). Those small summaries stay in the main script for cards, the home page
 * and <head> tags; the full guide text is loaded only when a guide is opened.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { ARTICLES_AR } from '../src/data/articles.ar';
import { ARTICLES_EN } from '../src/data/articles.en';
import { ARTICLES_TR } from '../src/data/articles.tr';

const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'data', 'articles.summary.ts');
const pick = (all: Record<string, { title: string; description: string; label?: string }>) =>
  Object.fromEntries(
    Object.entries(all).map(([k, v]) => [k, { title: v.title, description: v.description, ...(v.label ? { label: v.label } : {}) }])
  );

const data = { ar: pick(ARTICLES_AR), en: pick(ARTICLES_EN), tr: pick(ARTICLES_TR) };
const src = `// Generated by scripts/gen-article-summaries.ts — do not edit by hand.
export const ARTICLE_SUMMARIES: Record<'ar' | 'en' | 'tr', Record<string, { title: string; description: string; label?: string }>> = ${JSON.stringify(data, null, 2)};
`;
fs.writeFileSync(out, src, 'utf8');
console.log('article summaries written');
